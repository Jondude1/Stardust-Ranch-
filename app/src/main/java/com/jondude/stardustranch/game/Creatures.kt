package com.jondude.stardustranch.game

import kotlin.math.abs
import kotlin.math.max
import kotlin.math.min

/**
 * Hand-authored creature sprites for Stardust Ranch (original designs, one per species).
 *
 * Each creature is a right-facing material grid (one char per pixel, '.' transparent) drawn on a 32x32 canvas,
 * feet on row 30. The grid says WHAT each pixel is; [render] decides its tone from a consistent top-left light:
 * a height field from the silhouette gives each pixel a surface normal, which picks one of 4 tones from a
 * hue-shifted 5-tone ramp (cool purple shadows, warm highlights). Stray single pixels are cleaned up, outer
 * outlines use the darkest tone of the colour they touch (softer on the lit top-left edge), and frame 1 is a
 * breathing squash for the idle bounce.
 *
 * Materials:  a primary (species c1)   b secondary (c2)   c belly/cream   d horn/beak/claw   e leaf   f flame (glows)
 *             g crystal (glows)   uppercase A..G = that material forced into shadow   h = primary forced highlight
 * Details:    k pupil   w eye shine   y glowing eye   p blush   m dark line of primary   n dark line of secondary
 *             o contour line (darkest tone of whatever it sits in)
 */
object Creatures {
    private fun c(v: Long) = v.toInt()
    private val S = Px.Companion

    class Spr(val grid: List<String>, val pal: Map<Char, Int>)

    private val defs = HashMap<Int, Spr>()
    private fun def(id: Int, vararg pal: Pair<Char, Long>, g: () -> String) {
        defs[id] = Spr(g().trimIndent().lines().filter { it.isNotBlank() }, pal.associate { it.first to it.second.toInt() })
    }

    fun has(id: Int) = defs.containsKey(id)

    // ------------------------------------------------------------------ colour ramps
    private fun rgb2hsl(c: Int): FloatArray {
        val r = (c shr 16 and 0xFF) / 255f; val g = (c shr 8 and 0xFF) / 255f; val b = (c and 0xFF) / 255f
        val mx = max(r, max(g, b)); val mn = min(r, min(g, b)); val l = (mx + mn) / 2
        if (mx == mn) return floatArrayOf(0f, 0f, l)
        val d = mx - mn
        val s = if (l > 0.5f) d / (2 - mx - mn) else d / (mx + mn)
        var h = when (mx) { r -> (g - b) / d + (if (g < b) 6 else 0); g -> (b - r) / d + 2; else -> (r - g) / d + 4 } * 60f
        if (h >= 360f) h -= 360f
        return floatArrayOf(h, s, l)
    }

    private fun hsl2rgb(h: Float, s: Float, l: Float): Int {
        val ss = s.coerceIn(0f, 1f); val ll = l.coerceIn(0f, 1f)
        val q = if (ll < 0.5f) ll * (1 + ss) else ll + ss - ll * ss; val p = 2 * ll - q
        fun hue(t0: Float): Float {
            var t = t0; if (t < 0) t += 1; if (t > 1) t -= 1
            return when { t < 1f / 6 -> p + (q - p) * 6 * t; t < 0.5f -> q; t < 2f / 3 -> p + (q - p) * (2f / 3 - t) * 6; else -> p }
        }
        val hh = h / 360f
        val r = (hue(hh + 1f / 3) * 255).toInt(); val g = (hue(hh) * 255).toInt(); val b = (hue(hh - 1f / 3) * 255).toInt()
        return (0xFF shl 24) or (r.coerceIn(0, 255) shl 16) or (g.coerceIn(0, 255) shl 8) or b.coerceIn(0, 255)
    }

    private fun towards(h: Float, target: Float, amt: Float): Float {
        var d = target - h; if (d > 180) d -= 360; if (d < -180) d += 360
        val step = if (abs(d) < amt) d else amt * (if (d > 0) 1 else -1)
        return (h + step + 360f) % 360f
    }

    /** 5 tones: 0 outline, 1 shadow, 2 base, 3 light, 4 highlight. Shadows drift toward violet, lights toward gold. */
    fun ramp(base: Int): IntArray {
        val (h, s, l) = rgb2hsl(base).let { Triple(it[0], it[1], it[2]) }
        val grey = s < 0.1f
        val hs = if (grey) 245f else h; val hl = if (grey) 45f else h
        val sh = if (grey) 0.12f + s else s
        return intArrayOf(
            hsl2rgb(towards(hs, 255f, 34f), min(1f, sh * 0.9f + 0.12f), max(0.07f, l * 0.36f)),
            hsl2rgb(towards(hs, 255f, 14f), min(1f, sh * 0.95f + 0.04f), max(0.12f, l - 0.15f - (if (l > 0.8f) 0.04f else 0f))),
            base,
            hsl2rgb(towards(hl, 55f, 9f), s * 0.95f, min(0.94f, l + 0.09f)),
            hsl2rgb(towards(hl, 55f, 18f), s * 0.85f, min(0.98f, l + 0.19f))
        )
    }

    private val FLAME = intArrayOf(c(0xFF6E1A22), c(0xFFC8381E), c(0xFFF0742A), c(0xFFFFBC3A), c(0xFFFFF0A8))

    // ------------------------------------------------------------------ renderer
    private const val W = 32

    /** frames[0..1] facing right, [2..3] facing left (same contract as the old procedural sprites). */
    fun frames(sp: Species): Array<Px>? {
        val d = defs[sp.id] ?: return null
        val a = render(d, sp, 0); val b = render(d, sp, 1)
        return arrayOf(a, b, a.flipH(), b.flipH())
    }

    private fun render(d: Spr, sp: Species, frame: Int): Px {
        val gh = d.grid.size; val gw = d.grid.maxOf { it.length }
        // place grid on the canvas: feet on row 30, centred
        val ox = (W - gw) / 2; val oy = 31 - gh
        val g = Array(W) { CharArray(W) { '.' } }
        for ((y, row) in d.grid.withIndex()) for ((x, ch) in row.withIndex()) {
            val cx = x + ox; val cy = y + oy
            if (cx in 0 until W && cy in 0 until W) g[cy][cx] = ch
        }
        if (frame == 1) { // breathing squash: everything above the feet sinks one pixel
            val keep = 2
            for (y in 30 - keep downTo 1) g[y] = g[y - 1].copyOf()
            g[0] = CharArray(W) { '.' }
        }

        // materials
        val pal = d.pal
        fun col(ch: Char, def: Int) = pal[ch] ?: def
        val ramps = HashMap<Char, IntArray>()
        ramps['a'] = ramp(col('a', sp.c1))
        ramps['b'] = ramp(col('b', sp.c2))
        ramps['c'] = ramp(col('c', S.mix(S.lighten(sp.c1, 0.62f), c(0xFFFFF2D8), 0.35f)))
        ramps['d'] = ramp(col('d', c(0xFFF2E6CC)))
        ramps['e'] = ramp(col('e', c(0xFF62B44A)))
        ramps['f'] = pal['f']?.let { ramp(it) } ?: FLAME
        ramps['g'] = ramp(col('g', c(0xFFC8F0FF)))
        fun mat(ch: Char): Char? = when (ch) {
            in 'a'..'g' -> ch; in 'A'..'G' -> ch.lowercaseChar(); 'h', 'm' -> 'a'; 'n' -> 'b'; else -> null
        }
        val glows = setOf('f', 'g')

        // height field from the silhouette (two blur scales) -> normals
        val mask = Array(W) { y -> FloatArray(W) { x -> if (g[y][x] != '.') 1f else 0f } }
        fun blur(src: Array<FloatArray>, r: Int): Array<FloatArray> {
            val o = Array(W) { FloatArray(W) }
            for (y in 0 until W) for (x in 0 until W) {
                var s = 0f; var n = 0
                for (yy in y - r..y + r) for (xx in x - r..x + r) { n++; if (yy in 0 until W && xx in 0 until W) s += src[yy][xx] }
                o[y][x] = s / n
            }
            return o
        }
        val hs = blur(mask, 1); val hm = blur(mask, 2); val hl = blur(mask, 4)
        var top = W; var bot = 0
        for (y in 0 until W) for (x in 0 until W) if (g[y][x] != '.') { top = min(top, y); bot = max(bot, y) }
        val span = max(1, bot - top)

        val tone = Array(W) { IntArray(W) { -1 } }
        for (y in 0 until W) for (x in 0 until W) {
            val ch = g[y][x]; val m = mat(ch) ?: continue
            if (ch == 'm' || ch == 'n') { tone[y][x] = 0; continue }
            if (ch == 'h') { tone[y][x] = 4; continue }
            if (ch.isUpperCase()) { tone[y][x] = 1; continue }
            if (m in glows) { // brighter toward the core
                val core = hm[y][x] * 0.6f + hs[y][x] * 0.4f
                tone[y][x] = when { core > 0.9f -> 4; core > 0.72f -> 3; core > 0.5f -> 2; else -> 1 }
                continue
            }
            fun H(xx: Int, yy: Int): Float {
                val cx = xx.coerceIn(0, W - 1); val cy = yy.coerceIn(0, W - 1)
                return hm[cy][cx] * 0.55f + hl[cy][cx] * 0.45f
            }
            val gx = H(x + 1, y) - H(x - 1, y); val gy = H(x, y + 1) - H(x, y - 1)
            val yRel = (y - top).toFloat() / span
            val b = 0.5f + 1.55f * (gx * 0.75f + gy) + 0.22f * (0.45f - yRel) - (1f - hs[y][x]) * 0.25f
            tone[y][x] = when { b > 0.84f -> 4; b > 0.58f -> 3; b > 0.27f -> 2; else -> 1 }
        }
        // a highlight needs a lit neighbour beside it (no lonely sparkles)
        for (y in 0 until W) for (x in 0 until W) if (tone[y][x] == 4 && g[y][x] != 'h' && mat(g[y][x]) !in glows) {
            val n = listOf(tone.getOrNull(y)?.getOrNull(x - 1), tone.getOrNull(y)?.getOrNull(x + 1), tone.getOrNull(y - 1)?.getOrNull(x), tone.getOrNull(y + 1)?.getOrNull(x))
            if (n.none { it == 4 || it == 3 }) tone[y][x] = 3
        }
        // clean stray single pixels: a pixel whose same-material neighbours all agree on another tone joins them
        repeat(2) {
            for (y in 1 until W - 1) for (x in 1 until W - 1) {
                val ch = g[y][x]; val m = mat(ch) ?: continue
                if (ch.isUpperCase() || ch == 'm' || ch == 'n' || ch == 'h') continue
                val ns = ArrayList<Int>()
                for ((dx, dy) in listOf(-1 to 0, 1 to 0, 0 to -1, 0 to 1)) {
                    val c2 = g[y + dy][x + dx]
                    if (mat(c2) == m && !c2.isUpperCase() && c2 != 'm' && c2 != 'n') ns.add(tone[y + dy][x + dx])
                }
                if (ns.size >= 3 && ns.all { it == ns[0] } && ns[0] != tone[y][x]) tone[y][x] = ns[0]
            }
        }

        val p = Px(W, W)
        val pupil = col('k', c(0xFF22182E)); val shine = c(0xFFFFFFFF)
        val glowEye = col('y', c(0xFFFFE47A))
        val blush = S.mix(ramps['a']!![3], c(0xFFF0708C), 0.62f)
        for (y in 0 until W) for (x in 0 until W) {
            val ch = g[y][x]
            when (ch) {
                '.' -> {}
                'k' -> p.set(x, y, pupil)
                'w' -> p.set(x, y, shine)
                'y' -> p.set(x, y, glowEye)
                'p' -> p.set(x, y, col('p', blush))
                'o' -> {
                    val cnt = HashMap<Char, Int>()
                    for ((dx, dy) in listOf(-1 to 0, 1 to 0, 0 to -1, 0 to 1, -1 to -1, 1 to 1, 1 to -1, -1 to 1)) {
                        val m = mat(g.getOrNull(y + dy)?.getOrNull(x + dx) ?: '.') ?: continue
                        cnt[m] = (cnt[m] ?: 0) + 1
                    }
                    val m = cnt.maxByOrNull { it.value }?.key ?: 'a'
                    p.set(x, y, S.mix(ramps[m]!![0], ramps[m]!![1], 0.25f))
                }
                else -> { val m = mat(ch) ?: 'a'; p.set(x, y, ramps[m]!![tone[y][x].coerceIn(0, 4)]) }
            }
        }
        // outer outline: darkest tone of the touching colour; softened on the lit top-left side
        for (y in 0 until W) for (x in 0 until W) {
            if (g[y][x] != '.') continue
            var m: Char? = null; var lit = false
            for ((dx, dy) in listOf(0 to 1, 1 to 0, -1 to 0, 0 to -1)) {
                val ch = g.getOrNull(y + dy)?.getOrNull(x + dx) ?: continue
                if (ch == '.') continue
                m = mat(ch) ?: 'a'
                lit = dx > 0 || dy > 0 // the body lies right/below: this is a top-left edge
                break
            }
            val mm = m ?: continue
            val r = ramps[mm]!!
            p.set(x, y, if (lit) S.mix(r[0], r[1], 0.35f) else r[0])
        }
        return p
    }

