    private fun tone(b: Int, t: Long, f: Float) = S.mix(b, c(t), f)

    /** 4-tone ramp (outline, shadow, base, light): cool purple-shifted shadows, warm lights. */
    private fun ramp4(base: Long): IntArray {
        val b = c(base)
        return intArrayOf(S.shade(tone(b, 0xFF28183C, 0.62f), 0.72f), S.shade(tone(b, 0xFF3C286E, 0.30f), 0.86f), b, tone(b, 0xFFFFF0C8, 0.30f))
    }

    private fun personPal(skin: Long, hair: Long, shirt: Long, pants: Long, shoes: Long, acc: Long, band: Long,
                          buckle: Long = 0, apron: Long = 0): Map<Char, Int> {
        val m = HashMap<Char, Int>()
        val sk = c(skin)
        m['S'] = sk; m['K'] = tone(sk, 0xFFFFECD6, 0.35f); m['s'] = S.shade(tone(sk, 0xFFBE5A64, 0.28f), 0.88f)
        m['k'] = tone(sk, 0xFF5A2828, 0.65f); m['E'] = c(0xFF2A1E30); m['m'] = tone(sk, 0xFF963C3C, 0.45f); m['B'] = tone(sk, 0xFFF07878, 0.35f)
        fun put(keys: String, r: IntArray) { for (i in 0 until 4) if (keys[i] != '-') m[keys[i]] = r[i] }
        put("qwer", ramp4(hair)); put("abcd", ramp4(shirt)); put("pPnN", ramp4(pants)); put("z-Z-", ramp4(shoes))
        put("xXyY", ramp4(acc)); put("-Uu-", ramp4(band))
        if (buckle != 0L) m['Y'] = c(buckle)
        if (apron != 0L) put("g-G-", ramp4(apron))
        return m
    }

    private fun lay(p: Px, l: L, pal: Map<Char, Int>) = p.blit(Px.grid(l.rows, pal), 0, l.y)

    private fun shiftCols(p: Px, x0: Int, x1: Int, y0: Int, y1: Int, dy: Int) {
        val src = p.p.copyOf()
        for (x in x0..x1) for (y in y0..y1) { val sy = y - dy; p.p[y * p.w + x] = if (sy in y0..y1) src[sy * p.w + x] else 0 }
    }

    /** Raises one foot by 2px for the front/back walk. */
    private fun liftLeg(p: Px, x0: Int, x1: Int) {
        val src = p.p.copyOf()
        for (x in x0..x1) for (y in 25 until p.h) { val sy = y + 2; p.p[y * p.w + x] = if (sy < p.h) src[sy * p.w + x] else 0 }
    }

    /** d: 0 down, 1 up, 2 left. f: 0 idle, 1..4 walk cycle (1/3 are the lifted-foot frames with a 1px bob). */
    private fun person(style: Int, pal: Map<Char, Int>, d: Int, f: Int): Px {
        val img = Px(16, 32)
        if (d < 2) {
            lay(img, PERSON_LEGS, pal)
            if (f == 1) liftLeg(img, 4, 7)
            if (f == 3) liftLeg(img, 8, 11)
        } else lay(img, PERSON_SIDE_LEGS[intArrayOf(0, 1, 2, 3, 2)[f]], pal)
        val up = Px(16, 32)
        lay(up, PERSON_TORSO[d], pal)
        val step = f == 1 || f == 3
        if (d == 2 && step) {
            for (y in 17..22) for (x in 0 until 16) up.p[y * 16 + x] = 0
            lay(up, if (f == 1) PERSON_ARM_FWD else PERSON_ARM_BACK, pal)
        }
        if (d < 2 && step) {
            val s = if (f == 1) 1 else -1
            shiftCols(up, 1, 3, 16, 24, s); shiftCols(up, 12, 14, 16, 24, -s)
        }
        PERSON_OUTFIT[style]?.get(d)?.let { lay(up, it, pal) }
        lay(up, PERSON_HEAD[d], pal)
        lay(up, PERSON_HAIR[style][d], pal)
        img.blit(up, 0, if (step) -1 else 0)
        return img
    }

